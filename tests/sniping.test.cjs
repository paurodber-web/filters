const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8');
const source = html.slice(html.indexOf('function findSnipingBands('), html.indexOf('function showView('));
const context = vm.createContext({});
vm.runInContext(source, context);
const options = {minPrice:999,minCards:3,tolerance:100,mode:'coins'};
const rows = prices => prices.map((price,i)=>({id:i+1,price,position:'CB',alternate_positions:'CB;RB',nation:'Brazil',league:'Premier League',club:'Club',price_timestamp:'2026-10-07T12:00:00Z'}));
const search = (prices, changes={}) => context.findSnipingBands(rows(prices), {...options, position:'CB', ...changes});
assert.equal(search([1000,1050,1100]).length,1);
assert.equal(search([1000,1050,1100],{minPrice:1000}).length,0);
assert.equal(search([900,1050,1100,1150],{minPrice:1000}).length,0);
const bands=search([1100,1150,1200,5000,5050,5100],{minPrice:1000});
assert.equal(bands.length,2);
assert.ok(bands.every(b=>b.groupTotal===6&&b.groupMin===1100&&b.cards.length===3));
assert.equal(new Set(bands.flatMap(b=>b.cards.map(p=>p.id))).size,6);
for(const invalid of [null,undefined,0,-1,NaN,Infinity,''])assert.equal(search([1100,1150,invalid]).length,0);
assert.equal(search([100000,104000,105000],{minPrice:99999,mode:'percent',tolerance:5}).length,1);
assert.equal(search([100000,104000,105000],{minPrice:99999}).length,0);
assert.equal(search([1100,1100,1100],{tolerance:0}).length,1);
assert.equal(search([1100,1150]).length,0);
const numericDates=rows([1000,1050,1100]);numericDates.forEach(p=>p.price_timestamp=1791363600000);
assert.equal(context.findSnipingBands(numericDates,{...options,position:'CB'})[0].latest,1791363600000);
const duplicateRows=rows([1000,1050,1100]);duplicateRows.push(duplicateRows[0]);
const alternate=context.findSnipingBands(duplicateRows,{...options,position:'RB'});
assert.equal(alternate.length,1);assert.equal(alternate[0].groupTotal,3);
assert.equal(context.findSnipingBands(rows([1000,1050,1100]),{...options,club:'Other'}).length,0);
new vm.Script(html.match(/<script>([\s\S]*?)<\/script>/)[1]);
console.log('Sniping fixtures and generated JavaScript syntax passed.');
